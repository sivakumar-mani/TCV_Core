JOIN catv_package_remap map ON map.old_package_name = old_pm.package_name AND map.old_package_type = old_pm.package_type
JOIN cable_package_master new_pm ON new_pm.package_name = map.new_package_name AND new_pm.package_type = map.new_package_type
SET cp.package_id = new_pm.package_id,
    cp.package_type = CASE WHEN new_pm.package_type = 'BROADCAST' THEN 'BROADCASTER' ELSE new_pm.package_type END;

DELETE pm FROM cable_package_master pm
WHERE pm.service_category = 'CATV' AND pm.is_active = 0
  AND NOT EXISTS (SELECT 1 FROM cable_customer_packages cp WHERE cp.package_id = pm.package_id);
DROP TEMPORARY TABLE catv_package_remap;

