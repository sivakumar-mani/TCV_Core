CREATE TEMPORARY TABLE tcv_export_plan_2210 AS
SELECT cp.customer_package_id, cp.cable_customer_id, cp.package_id AS old_package_id,
       cp.package_price AS original_price, e.old_name, e.new_name,
       MIN(target.package_id) AS new_package_id, COUNT(target.package_id) AS target_count
FROM tcv_export_scope_2210 e
JOIN cable_tv_customers c ON CAST(c.customer_code AS CHAR) = e.customer_code
 AND COALESCE(c.legacy_customer_no, '') = e.legacy_no
 AND BINARY c.full_name = BINARY e.full_name
 AND UPPER(c.status) = 'ACTIVE' AND c.approval_status = 'APPROVED'
JOIN cable_customer_packages cp ON cp.cable_customer_id = c.cable_customer_id
 AND cp.is_active = 1 AND cp.approval_status = 'APPROVED'
 AND cp.package_price = e.original_price
JOIN cable_package_master old_pkg ON old_pkg.package_id = cp.package_id
 AND old_pkg.service_category = 'CATV'
 AND BINARY LOWER(TRIM(old_pkg.package_name)) = BINARY LOWER(e.old_name)
LEFT JOIN cable_customer_stbs stb ON stb.customer_stb_id = (
 SELECT s.customer_stb_id FROM cable_customer_stbs s
 WHERE s.cable_customer_id = c.cable_customer_id AND s.approval_status = 'APPROVED'
 ORDER BY s.customer_stb_id DESC LIMIT 1)
LEFT JOIN cable_stb_master sm ON sm.stb_master_id = stb.stb_master_id
LEFT JOIN cable_package_master target ON target.service_category = 'CATV'
 AND BINARY LOWER(TRIM(target.package_name)) = BINARY LOWER(e.new_name)
WHERE BINARY COALESCE(NULLIF(stb.stb_no, ''), sm.stb_number, '') = BINARY e.stb_no
GROUP BY cp.customer_package_id, cp.cable_customer_id, cp.package_id, cp.package_price,
         e.old_name, e.new_name;
/* Back up before applying; pause customer/package edits.
   Full-export guard: if ANY assignment no longer matches, or ANY target is unresolved,
   zero rows update. Re-run the preview to inspect. Never change prices to force a match.
*/
SELECT COUNT(*), COALESCE(SUM(target_count <> 1), 0)
 INTO @tcv_export_matches, @tcv_export_blocked FROM tcv_export_plan_2210;
UPDATE cable_customer_packages cp
JOIN tcv_export_plan_2210 p ON p.customer_package_id = cp.customer_package_id
 AND p.cable_customer_id = cp.cable_customer_id AND p.old_package_id = cp.package_id
 AND p.original_price = cp.package_price
SET cp.package_id = p.new_package_id, cp.updated_at = cp.updated_at
WHERE @tcv_export_matches = 1721 AND @tcv_export_blocked = 0
 AND p.target_count = 1 AND cp.is_active = 1 AND cp.approval_status = 'APPROVED';
SELECT ROW_COUNT() AS changed_assignments, @tcv_export_matches AS matched_export_assignments,
 @tcv_export_blocked AS blocked_target_assignments, 1721 AS expected_assignments;
