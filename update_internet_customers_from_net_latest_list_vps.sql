DROP TEMPORARY TABLE IF EXISTS net_latest_match;
CREATE TEMPORARY TABLE net_latest_match AS
SELECT i.*,c.internet_customer_id,
  (SELECT pm.package_id FROM internet_package_master pm
   WHERE pm.provider_category=i.network_type AND pm.is_active=1
     AND (LOWER(TRIM(pm.package_name))=LOWER(TRIM(i.package_name))
       OR RIGHT(LOWER(TRIM(pm.package_name)),CHAR_LENGTH(TRIM(i.package_name))+3)=CONCAT(' - ',LOWER(TRIM(i.package_name))))
   ORDER BY (pm.package_code IS NOT NULL) DESC,pm.package_id ASC LIMIT 1) package_id,
  CASE WHEN i.target_status='ACTIVE' THEN i.expiry_date ELSE NULL END start_date,
  CASE WHEN i.target_status='ACTIVE' AND i.network_type='KRISHI'
       THEN STR_TO_DATE(CONCAT(YEAR(DATE_ADD(i.expiry_date,INTERVAL 1 MONTH)),'-',LPAD(MONTH(DATE_ADD(i.expiry_date,INTERVAL 1 MONTH)),2,'0'),'-15'),'%Y-%m-%d')
       WHEN i.target_status='ACTIVE' AND i.network_type='RAILWIRE' THEN DATE_ADD(i.expiry_date,INTERVAL 30 DAY)
       ELSE NULL END end_date
FROM net_latest_import i
LEFT JOIN internet_customers c ON LOWER(TRIM(c.net_id))=LOWER(TRIM(i.username));
